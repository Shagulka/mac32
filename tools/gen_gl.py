#!/usr/bin/env python3
"""Generate src/gl_thunks.c: a host thunk for every legacy OpenGL function in
the macOS SDK headers, with i386 argument widths."""
import re, subprocess, sys

sdk = subprocess.run(['xcrun', '--show-sdk-path'], capture_output=True, text=True).stdout.strip()
hdrs = [f'{sdk}/System/Library/Frameworks/OpenGL.framework/Headers/{h}' for h in ('gl.h', 'glext.h')]
src = '\n'.join(open(h).read() for h in hdrs)
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)

U = {'GLenum', 'GLbitfield', 'GLuint', 'GLushort', 'GLubyte', 'GLboolean', 'GLhandleARB', 'GLuint64EXT_unused'}
I = {'GLint', 'GLsizei', 'GLshort', 'GLbyte', 'GLintptr', 'GLsizeiptr', 'GLintptrARB', 'GLsizeiptrARB', 'GLclampx', 'GLfixed'}
F = {'GLfloat', 'GLclampf'}
Dd = {'GLdouble', 'GLclampd'}
L = {'GLint64', 'GLuint64', 'GLint64EXT', 'GLuint64EXT'}
SPECIAL = {'glMapBuffer', 'glMapBufferARB', 'glUnmapBuffer', 'glUnmapBufferARB', 'glMapBufferRange',
           'glFlushMappedBufferRange', 'glFlushMappedBufferRangeAPPLE', 'glGetPointerv',
           'glGetBufferPointerv', 'glGetBufferPointervARB', 'glGetVertexAttribPointerv',
           'glGetVertexAttribPointervARB', 'glGetString', 'glGetStringi',
           'glShaderSource', 'glShaderSourceARB', 'glMultiDrawElements', 'glMultiDrawElementsEXT',
           'glMultiDrawElementsBaseVertex', 'glTransformFeedbackVaryingsEXT', 'glGetAttachedObjectsARB',
           'glGetPointervEXT', 'glGetTexParameterPointervAPPLE', 'glGetVertexAttribPointervNV'}

def code(t, ret=False):
    t = t.replace('const', '').strip()
    if '*' in t:
        return 'p'
    t = t.split()[-1] if t.split() else t
    if t == 'void': return 'v'
    if t == 'GLsync': return 'o'
    if t in U: return 'b' if (ret and t == 'GLboolean') else 'u'
    if t in I: return 'i'
    if t in F: return 'f'
    if t in Dd: return 'd'
    if t in L: return 'l'
    return None

out, seen, skipped = [], set(), []
for m in re.finditer(r'extern\s+([\w\s\*]+?)\s*\b(gl\w+)\s*\(([^)]*)\)\s*(?:OPENGL_\w+(?:\([^)]*\))?\s*)*;', src):
    rt, name, args = m.group(1), m.group(2), m.group(3).strip()
    if name in seen or name in SPECIAL: continue
    rc = code(rt, True)
    if rc == 'p' or rc is None:
        skipped.append(name); continue
    sig = ''
    ok = True
    if args and args != 'void':
        for a in args.split(','):
            a = re.sub(r'\[\d*\]', '*', a.strip())
            a = re.sub(r'\b\w+$', '', a).strip() if not a.endswith('*') else a
            c = code(a)
            if c is None or c == 'v':
                ok = False; break
            sig += c
    if not ok:
        skipped.append(name); continue
    seen.add(name)
    out.append(f'\tG("_{name}", NULL, "{rc}:{sig}"),')

with open('src/gl_thunks.c', 'w') as f:
    f.write('// Generated by tools/gen_gl.py from the SDK OpenGL headers. Do not edit.\n')
    f.write('// Functions are looked up at startup; ones this macOS lacks are dropped.\n')
    f.write('#include <dlfcn.h>\n#include "thunks.h"\n\n')
    f.write('static struct hfn gl[] = {\n' + '\n'.join(out) + '\n};\n\n')
    f.write('''void thunks_gl_gen_init(void)
{
	size_t n = 0;
	for (size_t i = 0; i < sizeof gl / sizeof gl[0]; i++) {
		gl[i].fn = dlsym(RTLD_DEFAULT, gl[i].name + 1);
		if (gl[i].fn) gl[n++] = gl[i];
	}
	thunk_register(gl, n);
	LOG("%zu OpenGL functions available\\n", n);
}
''')
print(f'{len(out)} functions, skipped {len(skipped)}: {" ".join(skipped)}', file=sys.stderr)
